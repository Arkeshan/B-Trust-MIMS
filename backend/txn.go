// TxnRequest defines the expected JSON payload.
// Notice StaffPersonID is REMOVED to prevent client-side spoofing.
type TxnRequest struct {
	AccountNo string          `json:"account_no"`
	Amount    decimal.Decimal `json:"amount"`
}

// ProcessTransaction handles POST /api/txn/deposit and POST /api/txn/withdraw
func ProcessTransaction(db *sql.DB, txnType string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		// 1. Prevent memory leaks
		defer r.Body.Close()

		if r.Method != http.MethodPost {
			http.Error(w, "Only POST requests are allowed", http.StatusMethodNotAllowed)
			return
		}

		var req TxnRequest
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			log.Printf("[API Error] JSON Decode Failed: %v", err)
			http.Error(w, fmt.Sprintf("Invalid JSON format: %v", err), http.StatusBadRequest)
			return
		}

		// 2. Security: Extract staff ID from the secure session/JWT context.
		// (Mocked function: In reality, you'd pull this from r.Context() or your auth middleware)
		secureStaffID := getStaffIDFromSession(r)
		if secureStaffID == 0 {
			http.Error(w, "Unauthorized: Invalid Session", http.StatusUnauthorized)
			return
		}

		// 3. Begin an ACID-compliant Database Transaction
		tx, err := db.Begin()
		if err != nil {
			http.Error(w, "Server error", http.StatusInternalServerError)
			return
		}
		// If anything fails, this safely rolls back all changes. If tx.Commit() succeeds, this is ignored.
		defer tx.Rollback()

		// 4. Insert the transaction
		insertQuery := `INSERT INTO TRANSACTION (account_no, staff_person_id, txn_type, amount, balance_after) 
		                VALUES (?, ?, ?, ?, 0.00)`

		result, err := tx.Exec(insertQuery, req.AccountNo, secureStaffID, txnType, req.Amount.String())
		if err != nil {
			http.Error(w, fmt.Sprintf("Transaction Denied: %v", err), http.StatusBadRequest)
			return
		}

		// LastInsertId is thread-safe in Go (it reads the ID generated by this specific connection)
		txnID, err := result.LastInsertId()
		if err != nil {
			http.Error(w, "Failed to retrieve transaction ID", http.StatusInternalServerError)
			return
		}

		// 5. Fetch the updated balance generated by the SQL Trigger using the locked transaction (tx)
		var updatedBalance decimal.Decimal
		selectQuery := `SELECT balance_after FROM TRANSACTION WHERE txn_id = ?`

		if err := tx.QueryRow(selectQuery, txnID).Scan(&updatedBalance); err != nil {
			http.Error(w, "Failed to fetch updated balance", http.StatusInternalServerError)
			return
		}

		// 6. Commit the transaction to officially save the data
		if err := tx.Commit(); err != nil {
			http.Error(w, "Failed to finalize transaction", http.StatusInternalServerError)
			return
		}

		// 7. Return the successful response
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusOK)
		json.NewEncoder(w).Encode(map[string]any{
			"status":      "success",
			"message":     fmt.Sprintf("%s successful.", txnType),
			"account_no":  req.AccountNo,
			"amount":      req.Amount,
			"new_balance": updatedBalance,
		})
	}
}

